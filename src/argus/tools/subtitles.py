"""Frame-accurate "Safe Pop" karaoke subtitles in ASS format.

Style: one word per frame-ish cue, the active word in bright yellow,
centered at eye level, bold wide font, thick black outline, no box.
"""

from __future__ import annotations

import json
from pathlib import Path

from ..config import CONFIG

# #FFE066 -> ASS &HAABBGGRR
HIGHLIGHT_ASS = "&H0066E0FF"
DEFAULT_FONT_SIZE = 110
DEFAULT_MARGIN_V = 420


def _ass_time(seconds: float) -> str:
    seconds = max(0.0, seconds)
    h = int(seconds // 3600)
    m = int(seconds % 3600 // 60)
    s = seconds % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def _quantize(t: float, fps: float) -> float:
    return round(t * fps) / fps


def _load_words(timestamps_json_path: str | Path) -> list[dict]:
    data = json.loads(Path(timestamps_json_path).read_text(encoding="utf-8"))
    if isinstance(data, dict):
        data = data.get("words") or data.get("timestamps") or []
    words = []
    for item in data:
        word = str(item.get("word", "")).strip()
        if not word:
            continue
        words.append({
            "word": word,
            "start": float(item["start"]),
            "end": float(item["end"]),
        })
    if not words:
        raise ValueError("no usable {word,start,end} entries in timestamps file")
    return words


def build_pop_subtitles(
    timestamps_json_path: str | Path,
    output_ass_path: str | Path,
    *,
    fps: float | None = None,
    font: str = "Arial Black",
    font_size: int = DEFAULT_FONT_SIZE,
    margin_v: int = DEFAULT_MARGIN_V,
    highlight_color: str = HIGHLIGHT_ASS,
) -> dict:
    """Generate the ASS subtitle file; returns a small stats dict."""
    fps = fps or CONFIG.fps
    words = _load_words(timestamps_json_path)

    style = (
        f"Style: Pop,{font},{font_size},{highlight_colour_ass(highlight_color)},"
        f"&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,9,3,2,80,80,{margin_v},1"
    )

    lines: list[str] = []
    for item in words:
        start = _quantize(item["start"], fps)
        end = max(start + 1.0 / fps, _quantize(item["end"], fps))
        text = item["word"].replace("{", "(").replace("}", ")")
        lines.append(f"Dialogue: 0,{_ass_time(start)},{_ass_time(end)},Pop,,0,0,0,,{text}")

    content = "\n".join([
        "[Script Info]",
        "; Generated by ARGUS - Safe Pop karaoke style",
        "ScriptType: v4.00+",
        f"PlayResX: {CONFIG.width}",
        f"PlayResY: {CONFIG.height}",
        "WrapStyle: 2",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
        "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
        "Alignment, MarginL, MarginR, MarginV, Encoding",
        style,
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
        *lines,
        "",
    ])

    out = Path(output_ass_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    return {"output": str(out), "words": len(words), "fps": fps, "style": "Safe Pop"}


def highlight_colour_ass(color: str) -> str:
    """Accept `&H0066E0FF` or `#FFE066` and return a valid ASS colour."""
    color = color.strip()
    if color.startswith("&H") or color.startswith("&h"):
        return color.upper().replace("&H", "&H", 1)
    if color.startswith("#") and len(color) == 7:
        r, g, b = color[1:3], color[3:5], color[5:7]
        return f"&H00{b}{g}{r}".upper()
    raise ValueError(f"unsupported colour: {color!r}")
