"""Frame-accurate karaoke subtitles in ASS format.

One word per cue, centered at eye level. Styles:
  clean   — white text, soft translucent shadow, modern (default)
  outline — white with a thick black outline, classic shorts
  pop     — legacy bright-yellow highlight (#FFE066)
"""

from __future__ import annotations

import json
from pathlib import Path

from ..config import CONFIG

DEFAULT_FONT_SIZE = 110
DEFAULT_MARGIN_V = 420

STYLES: dict[str, dict] = {
    "clean": {
        "primary": "#FFFFFF", "outline": "#000000", "outline_w": 2,
        "shadow_w": 2, "back": "&H96000000", "font": "Arial",
    },
    "outline": {
        "primary": "#FFFFFF", "outline": "#000000", "outline_w": 8,
        "shadow_w": 3, "back": "&H00000000", "font": "Arial Black",
    },
    "pop": {
        "primary": "#FFE066", "outline": "#000000", "outline_w": 9,
        "shadow_w": 3, "back": "&H00000000", "font": "Arial Black",
    },
}


def _ass_time(seconds: float) -> str:
    seconds = max(0.0, seconds)
    h = int(seconds // 3600)
    m = int(seconds % 3600 // 60)
    s = seconds % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def _quantize(t: float, fps: float) -> float:
    return round(t * fps) / fps


def _load_words(timestamps_json_path: str | Path) -> list[dict]:
    data = json.loads(Path(timestamps_json_path).read_text(encoding="utf-8"))
    if isinstance(data, dict):
        data = data.get("words") or data.get("timestamps") or []
    words = []
    for item in data:
        word = str(item.get("word", "")).strip()
        if not word:
            continue
        words.append({
            "word": word,
            "start": float(item["start"]),
            "end": float(item["end"]),
        })
    if not words:
        raise ValueError("no usable {word,start,end} entries in timestamps file")
    return words


def hex_to_ass(color: str) -> str:
    """`#RRGGBB` or `&HAABBGGRR` -> ASS `&HAABBGGRR`."""
    color = color.strip()
    if color.startswith("&H") or color.startswith("&h"):
        return color.upper()
    if color.startswith("#") and len(color) == 7:
        r, g, b = color[1:3], color[3:5], color[5:7]
        return f"&H00{b}{g}{r}".upper()
    raise ValueError(f"unsupported colour: {color!r}")


def _norm_word(w: str) -> str:
    import re as _re

    return _re.sub(r"[^\w%₽$€]", "", w.lower().replace("ё", "е"))


def build_pop_subtitles(
    timestamps_json_path: str | Path,
    output_ass_path: str | Path,
    *,
    style: str = "clean",
    font: str | None = None,
    font_size: int = DEFAULT_FONT_SIZE,
    margin_v: int = DEFAULT_MARGIN_V,
    highlight_color: str = "#FFE066",
    accent: list[str] | None = None,
    accent_color: str = "#4DA3FF",
    fps: float | None = None,
) -> dict:
    """Generate the ASS subtitle file; returns a small stats dict.

    accent: list of words (str, "prefix*" or "*" for all) rendered in
    accent_color — same semantics as the montazh skills' subs.accent.
    """
    fps = fps or CONFIG.fps
    if style not in STYLES:
        raise ValueError(f"unknown style {style!r}; expected one of {sorted(STYLES)}")
    preset = dict(STYLES[style])
    if style == "pop":
        preset["primary"] = highlight_color
    font = font or preset["font"]
    words = _load_words(timestamps_json_path)

    acc = list(accent or [])
    acc_bgr = hex_to_ass(accent_color).replace("&H", "&H", 1)

    def _is_accent(word: str) -> bool:
        n = _norm_word(word)
        for x in acc:
            if x.endswith("*"):
                if n.startswith(_norm_word(x.rstrip("*"))):
                    return True
            elif n == _norm_word(x):
                return True
        return False

    style_line = (
        f"Style: Argus,{font},{font_size},{hex_to_ass(preset['primary'])},"
        f"&H00FFFFFF,{hex_to_ass(preset['outline'])},{preset['back']},"
        f"-1,0,0,0,100,100,0,0,1,{preset['outline_w']},{preset['shadow_w']},"
        f"2,80,80,{margin_v},1"
    )

    lines: list[str] = []
    for item in words:
        start = _quantize(item["start"], fps)
        end = max(start + 1.0 / fps, _quantize(item["end"], fps))
        text = item["word"].replace("{", "(").replace("}", ")")
        if acc and _is_accent(item["word"]):
            text = "{\\1c&H" + acc_bgr[4:] + "&}" + text
        lines.append(f"Dialogue: 0,{_ass_time(start)},{_ass_time(end)},Argus,,0,0,0,,{text}")

    content = "\n".join([
        "[Script Info]",
        "; Generated by ARGUS - karaoke subtitles",
        "ScriptType: v4.00+",
        f"PlayResX: {CONFIG.width}",
        f"PlayResY: {CONFIG.height}",
        "WrapStyle: 2",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
        "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
        "Alignment, MarginL, MarginR, MarginV, Encoding",
        style_line,
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
        *lines,
        "",
    ])

    out = Path(output_ass_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    return {"output": str(out), "words": len(words), "fps": fps, "style": style, "font": font}
